# Benchmark case and solver-variant definitions for the GPU solver campaign.
#
# Shared by harness.jl (which composes them into a per-run input deck in a
# temporary directory) and write_inputs.jl (which materialises them as
# standalone decks under benchmark/inputs/).  Edit here, then regenerate the
# checked-in decks with:  julia benchmark/write_inputs.jl

const REPO = normpath(joinpath(@__DIR__, ".."))

# --------------------------------------------------------------------------- #
# Case definitions
# --------------------------------------------------------------------------- #

# Torsion cylinder (530,523 DOF): IC-driven for dynamics, twist-BC for QS.
const TORSION_MESH = joinpath(REPO, "examples", "meshes", "torsion", "torsion.g")
const CUBE_MESH    = joinpath(REPO, "examples", "mechanics", "quasistatic",
                              "cube", "cube.g")
# Generated by benchmark/meshgen.jl 100 (3.09M DOF); regenerate if absent.
const CUBE100_MESH = joinpath(REPO, "benchmark", "meshes", "cube100.g")
const CUBE64_MESH  = joinpath(REPO, "benchmark", "meshes", "cube64.g")
const CUBE80_MESH  = joinpath(REPO, "benchmark", "meshes", "cube80.g")

material_block(name) = """
model:
  type: solid mechanics
  material:
    blocks:
      $name: neohookean
    neohookean:
      elastic modulus: 1.0e9
      density: 1000.0
      Poisson's ratio: 0.25
"""

function case_yaml(case::String)
    if case == "torsion-newmark"
        # 4 implicit steps at dt = 5e-5: the configuration the July 2026
        # footprint study used, large enough that CG has real work per step.
        return ("torsion.g", TORSION_MESH, material_block("torsion") * """
time integrator:
  type: newmark
  time step: 5.0e-5
  gamma: 0.5
  final time: 2.0e-4
  initial time: 0.0
  beta: 0.25
initial conditions:
  velocity:
    - node set: nsall
      function: "a=8000; -a*y*z"
      component: x
    - node set: nsall
      function: "a=8000; a*x*z"
      component: y
    - node set: nsall
      function: "0.0"
      component: z
""")
    elseif case == "torsion-qs"
        # Quasistatic twist: base clamped, free end rotated by θ(t) = 0.05·t
        # about z, ramped over 4 load steps.
        return ("torsion.g", TORSION_MESH, material_block("torsion") * """
time integrator:
  type: quasi static
  initial time: 0.0
  final time: 1.0
  time step: 0.25
boundary conditions:
  dirichlet:
    - node set: "-Z"
      component: x
      function: "0.0"
    - node set: "-Z"
      component: y
      function: "0.0"
    - node set: "-Z"
      component: z
      function: "0.0"
    - node set: "+Z"
      component: x
      function: "th=0.05; x*(cos(th*t)-1.0) - y*sin(th*t)"
    - node set: "+Z"
      component: y
      function: "th=0.05; x*sin(th*t) + y*(cos(th*t)-1.0)"
    - node set: "+Z"
      component: z
      function: "0.0"
""")
    elseif case in ("cube64-qs", "cube80-qs", "cube64-newmark", "cube80-newmark")
        meshfile, meshpath = startswith(case, "cube64") ?
            ("cube64.g", CUBE64_MESH) : ("cube80.g", CUBE80_MESH)
        ti = endswith(case, "-qs") ? """
time integrator:
  type: quasi static
  initial time: 0.0
  final time: 1.0
  time step: 0.5
""" : """
time integrator:
  type: newmark
  time step: 5.0e-5
  gamma: 0.5
  final time: 1.0e-4
  initial time: 0.0
  beta: 0.25
"""
        return (meshfile, meshpath, material_block("cube") * ti * """
boundary conditions:
  dirichlet:
    - node set: nsx-
      component: x
      function: "0.0"
    - node set: nsy-
      component: y
      function: "0.0"
    - node set: nsz-
      component: z
      function: "0.0"
    - node set: nsz+
      component: z
      function: "1.0e-3 * t"
""")
    elseif case == "cube100-qs"
        # 3.09M-DOF scaling case: uniaxial stretch, 2 load steps.
        return ("cube100.g", CUBE100_MESH, material_block("cube") * """
time integrator:
  type: quasi static
  initial time: 0.0
  final time: 1.0
  time step: 0.5
boundary conditions:
  dirichlet:
    - node set: nsx-
      component: x
      function: "0.0"
    - node set: nsy-
      component: y
      function: "0.0"
    - node set: nsz-
      component: z
      function: "0.0"
    - node set: nsz+
      component: z
      function: "1.0e-3 * t"
""")
    elseif case == "cube100-newmark"
        # 3.09M-DOF dynamic case: BC-driven, 2 implicit steps.
        return ("cube100.g", CUBE100_MESH, material_block("cube") * """
time integrator:
  type: newmark
  time step: 5.0e-5
  gamma: 0.5
  final time: 1.0e-4
  initial time: 0.0
  beta: 0.25
boundary conditions:
  dirichlet:
    - node set: nsz-
      component: z
      function: "0.0"
    - node set: nsz+
      component: z
      function: "1.0e-3 * t / 1.0e-4"
""")
    elseif case == "cube-newmark" || case == "cube-qs"
        # Small smoke-test case (81 DOF): validates the harness end to end.
        ti = case == "cube-newmark" ? """
time integrator:
  type: newmark
  time step: 1.0e-5
  gamma: 0.5
  final time: 2.0e-5
  initial time: 0.0
  beta: 0.25
""" : """
time integrator:
  type: quasi static
  initial time: 0.0
  final time: 1.0
  time step: 0.5
"""
        return ("cube.g", CUBE_MESH, material_block("cube") * ti * """
boundary conditions:
  dirichlet:
    - side set: ssx-
      component: x
      function: "0.0"
    - side set: ssy-
      component: y
      function: "0.0"
    - side set: ssz-
      component: z
      function: "0.0"
    - side set: ssz+
      component: z
      function: "1.0e-3 * t"
""")
    else
        error("Unknown case \"$case\".")
    end
end

# --------------------------------------------------------------------------- #
# Solver variant definitions
# --------------------------------------------------------------------------- #

const NEWTON_TERM = """
  termination:
    fail when any:
      - maximum iterations: 30
    converge when any:
      - absolute residual: 1.0e-6
      - relative residual: 1.0e-10
"""

const LBFGS_TERM = """
  termination:
    fail when any:
      - maximum iterations: 500
    converge when any:
      - absolute residual: 1.0e-6
      - relative residual: 1.0e-10
"""

function variant_yaml(variant::String)
    startswith(variant, "gpu-") || startswith(variant, "cpu-") ||
        error("Unknown variant \"$variant\".")
    kind = variant[5:end]

    if kind == "direct"
        return """
solver:
  type: newton
$(NEWTON_TERM)  linear solver:
    type: direct
"""
    elseif kind == "lbfgs"
        return """
solver:
  type: newton
$(LBFGS_TERM)  linear solver:
    type: lbfgs
    history size: 10
"""
    elseif startswith(kind, "cg-")
        precond = kind[4:end]
        precond in ("jacobi", "chebyshev", "ic", "amg") ||
            error("Unknown preconditioner \"$precond\".")
        return """
solver:
  type: newton
$(NEWTON_TERM)  linear solver:
    type: iterative
    tolerance: 1.0e-8
    maximum iterations: 1000
    preconditioner:
      type: $precond
"""
    else
        error("Unknown variant \"$variant\".")
    end
end
