# Materialise the benchmark input decks as standalone YAML files under
# benchmark/inputs/, one per (case, variant) pair run in the GPU solver
# campaign (see benchmark_report.md).  Each deck is directly runnable:
#
#   bin/carina benchmark/inputs/<case>-<variant>.yaml
#
# The `device:` key pins the backend the study used (rocm for gpu-* decks);
# override with bin/carina's --device flag.  Cube meshes must exist first —
# see benchmark/README.md.
#
# Usage:  julia benchmark/write_inputs.jl     (no project environment needed)

include(joinpath(@__DIR__, "cases.jl"))

# Every (case, variant) pair that produced a record in benchmark/results/,
# plus the pairs that failed structurally (torsion-qs gpu-lbfgs diverges,
# cube80-qs cpu-cg-amg exhausts host memory) — those failures are findings
# of the study and should be reproducible too.  cube-qs is the 81-DOF smoke
# case for checking a setup end to end in seconds.
const STUDY = [
    ("torsion-newmark", ["gpu-cg-jacobi", "gpu-cg-chebyshev", "gpu-lbfgs",
                         "cpu-cg-jacobi", "cpu-cg-ic", "cpu-cg-amg", "cpu-direct"]),
    ("torsion-qs",      ["gpu-cg-amg", "gpu-cg-jacobi", "gpu-cg-chebyshev",
                         "gpu-lbfgs", "cpu-cg-jacobi", "cpu-cg-ic", "cpu-cg-amg",
                         "cpu-direct"]),
    ("cube64-qs",       ["gpu-cg-amg", "gpu-cg-jacobi", "cpu-cg-amg",
                         "cpu-cg-jacobi"]),
    ("cube80-qs",       ["gpu-cg-amg", "gpu-cg-jacobi", "cpu-cg-amg",
                         "cpu-cg-jacobi"]),
    ("cube80-newmark",  ["gpu-cg-jacobi", "cpu-cg-jacobi"]),
    ("cube-qs",         ["gpu-cg-jacobi", "cpu-direct"]),
]

function write_inputs(dir::String=joinpath(@__DIR__, "inputs"))
    mkpath(dir)
    n = 0
    for (case, variants) in STUDY, variant in variants
        _, meshpath, case_body = case_yaml(case)
        device = startswith(variant, "gpu-") ? "rocm" : "cpu"
        name = "$case-$variant"
        deck = """
        # $name — generated by benchmark/write_inputs.jl from benchmark/cases.jl.
        # Regenerate after editing cases.jl; do not edit this file by hand.
        type: single
        device: $device
        input mesh file: $(relpath(meshpath, dir))
        output mesh file: $name.e
        """ * case_body * variant_yaml(variant)
        write(joinpath(dir, "$name.yaml"), deck)
        n += 1
    end
    println("Wrote $n decks to $dir")
end

if abspath(PROGRAM_FILE) == @__FILE__
    write_inputs()
end
