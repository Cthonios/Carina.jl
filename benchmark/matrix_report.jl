# Render the performance matrix as Markdown tables.
#
#   julia benchmark/matrix_report.jl            # prints to stdout
#   julia benchmark/matrix_report.jl --write    # rewrites benchmark/MATRIX.md
#
# Reads every benchmark/results/matrix/*.jsonl, groups by device, and emits
# one table per part of the matrix.  No dependency: the records are flat JSON
# objects, one per line, and the fields this needs are pulled out directly.
# The tables are the only rendering of the matrix in the repository, so this
# is what to rerun after adding a device or a point.

using Printf

const REPO   = dirname(@__DIR__)
const MATRIX = joinpath(REPO, "benchmark", "results", "matrix")
const OUT    = joinpath(REPO, "benchmark", "MATRIX.md")

# --------------------------------------------------------------------------
# Reading
# --------------------------------------------------------------------------
function field(line::String, key::String)
    m = match(Regex("\"" * key * "\":(\\[[^\\]]*\\]|\"[^\"]*\"|[^,}]+)"), line)
    m === nothing && return nothing
    v = strip(String(m.captures[1]))
    startswith(v, "\"") && return String(strip(v, '"'))
    v == "null" && return nothing
    v == "true" && return true
    v == "false" && return false
    startswith(v, "[") && return nothing        # arrays are not rendered
    return tryparse(Float64, v)
end

struct Rec
    regime::String; case::String; variant::String
    n_dofs::Float64; device::String; gpu::String; host::String
    commit::String; threads::Int
    t_total::Union{Nothing,Float64}; steady::Union{Nothing,Float64}
    per_step_ms::Union{Nothing,Float64}; cg::Union{Nothing,Float64}
    amg_build::Union{Nothing,Float64}; vram::Union{Nothing,Float64}
    ok::Bool; failure::String
    timestamp::Float64
end

function read_matrix()
    recs = Rec[]
    for f in sort(filter(x -> endswith(x, ".jsonl"), readdir(MATRIX)))
        for line in eachline(joinpath(MATRIX, f))
            isempty(strip(line)) && continue
            g(k) = field(line, k)
            push!(recs, Rec(g("regime"), g("case"), g("variant"),
                            something(g("n_dofs"), 0.0), g("device"), something(g("gpu"), ""),
                            g("host"), something(g("commit"), "?"), round(Int, something(g("threads"), 0.0)),
                            g("t_total_s"), g("steady_step_s"), g("per_step_ms"), g("cg_total"),
                            g("amg_build_s"), g("vram_live_bytes"),
                            g("ok") === true, something(g("failure"), ""),
                            something(g("timestamp"), 0.0)))
        end
    end
    # Newest first, so `findfirst` on any cell is the most recent measurement.
    # A device file is appended to when a point is rerun; the earlier rows are
    # kept there until they are moved to ../archive, and a rerun supersedes
    # them in the tables either way.
    sort!(recs; by = r -> r.timestamp, rev = true)
    return recs
end

# Display label for a device, and the order the columns appear in: by
# increasing memory bandwidth, which is the order the report reasons in.
label(r::Rec) = r.device == "cpu" ? "CPU ($(r.host))" :
    replace(replace(r.gpu, "NVIDIA " => ""), "AMD Radeon " => "", "Tesla " => "",
            "-PCIE-40GB" => "", "-PCIE-32GB" => "")
const ORDER = ["RX 7600", "L4", "V100", "A100"]
devrank(l) = something(findfirst(==(l), ORDER), length(ORDER) + 1)

fmt(x::Nothing) = "—"
fmt(x::Float64; d = 1) = @sprintf("%.*f", d, x)
gb(x) = x === nothing ? "—" : @sprintf("%.2f", x / 1e9)

function md_table(io, header, rows)
    println(io, "| ", join(header, " | "), " |")
    println(io, "|", join(("---:" for _ in header), "|"), "|")
    for r in rows
        println(io, "| ", join(r, " | "), " |")
    end
    println(io)
end

# --------------------------------------------------------------------------
# Tables
# --------------------------------------------------------------------------
function render(io, recs)
    devices = sort(unique(label.(recs)); by = devrank)
    hosts   = Dict(label(r) => r.host for r in recs)
    # Commits a device's rendered rows come from, newest first.
    commits(d) = unique(r.commit for r in recs if label(r) == d)

    println(io, "# Carina performance matrix\n")
    println(io, "Generated by `benchmark/matrix_report.jl` from `benchmark/results/matrix/`.")
    println(io, "Do not edit by hand; rerun the generator.\n")
    println(io, "Every row was produced by `benchmark/matrix.jl` under Julia 1.13,",
            " one fresh process per point, with the device's memory in use recorded",
            " as clean before each; where a point has been rerun the most recent",
            " measurement is shown. Devices and the commits their rows come from: ",
            join(("$d on `$(hosts[d])` (" * join(("`$c`" for c in commits(d)), ", ") * ")"
                  for d in devices), ", "), ".\n")
    println(io, "The RX 7600 rows carry the ROCm workgroup bound of `f5082b4`",
            " (`bin/rocm_workgroup_bound.jl`); its earlier rows are in `results/archive/`.\n")

    # -- Spine ---------------------------------------------------------------
    println(io, "## Spine: one mesh, three regimes\n")
    println(io, "The torsion bar (`torsion.g`, 530,523 DOF, 160,000 HEX8) under all three",
            " time integrators. A device's three rows differ only by the integrator.\n")
    println(io, "### Quasi-static (4 load steps, Newton + CG)\n")
    rows = []
    for v in ("gpu-cg-amg", "gpu-cg-jacobi")
        cells = Any[v]
        for d in devices
            r = findfirst(x -> label(x) == d && x.case == "torsion-qs" && x.variant == v, recs)
            push!(cells, r === nothing ? "—" :
                  (recs[r].ok ? "$(fmt(recs[r].t_total)) s / $(fmt(recs[r].steady)) s / $(round(Int, recs[r].cg))" : "failed: $(recs[r].failure)"))
        end
        push!(rows, cells)
    end
    md_table(io, vcat(["variant"], devices), rows)
    println(io, "Cells are total wall / steady step (median of steps 2–4) / total CG iterations.\n")

    println(io, "### Implicit dynamics (Newmark, Δt = 5e-5, 4 steps)\n")
    rows = []
    for v in ("gpu-cg-jacobi", "gpu-cg-amg")
        cells = Any[v]
        for d in devices
            r = findfirst(x -> label(x) == d && x.case == "torsion-newmark" && x.variant == v, recs)
            push!(cells, r === nothing ? "—" :
                  (recs[r].ok ? "$(fmt(recs[r].t_total)) s / $(fmt(recs[r].steady)) s / $(round(Int, recs[r].cg))" : "failed: $(recs[r].failure)"))
        end
        push!(rows, cells)
    end
    md_table(io, vcat(["variant"], devices), rows)

    println(io, "### Explicit dynamics (central difference, N = 20)\n")
    cells = Any["ms / step"]
    for d in devices
        rs = filter(x -> label(x) == d && x.regime == "explicit" && abs(x.n_dofs - 530523) < 1, recs)
        # The two most recent: one spine and one ladder measurement.
        rs = rs[1:min(2, end)]
        push!(cells, isempty(rs) ? "—" :
              join((fmt(x.per_step_ms; d = 2) for x in rs), " · "))
    end
    md_table(io, vcat(["quantity"], devices), [cells])
    println(io, "Two values per device are the spine and ladder measurements of the same",
            " point, taken minutes apart; their spread is the run-to-run repeatability.\n")

    # -- Ladder --------------------------------------------------------------
    println(io, "## Explicit ladder: cost per step against refinement\n")
    println(io, "Fixed CFL, so cost per step is the only thing that varies. ms / step.\n")
    Ns = sort(unique(round(Int, x.n_dofs) for x in recs if x.regime == "explicit"))
    rows = []
    for n in Ns
        cells = Any[@sprintf("%.2fM", n / 1e6)]
        for d in devices
            rs = filter(x -> label(x) == d && x.regime == "explicit" && round(Int, x.n_dofs) == n, recs)
            rs = rs[1:min(2, end)]
            push!(cells, isempty(rs) ? "—" : fmt(minimum(x.per_step_ms for x in rs); d = 2))
        end
        push!(rows, cells)
    end
    md_table(io, vcat(["DOF"], devices), rows)

    println(io, "### ns per element, N ≥ 28\n")
    println(io, "Per-element cost once launch overhead is amortized; flat means no scaling cliff.\n")
    cells = Any["ns / element"]
    for d in devices
        rs = filter(x -> label(x) == d && x.regime == "explicit" && x.n_dofs >= 1.4e6, recs)
        rs = unique(x -> round(Int, x.n_dofs), rs)      # most recent per size
        # n_elems = 20 N^3 and n_dofs = 3 (N+1)^2 (20N+1).  N is recovered by
        # matching the formula exactly: the cube-root shortcut rounds to N+1 at
        # every size on this family, because the (N+1)^2 (20N+1) factors sit
        # above 20 N^3 by a near-constant 0.68 in the root.
        ns = Float64[]
        for x in rs
            N = findfirst(n -> 3 * (n + 1)^2 * (20n + 1) == round(Int, x.n_dofs), 1:200)
            N === nothing && continue
            push!(ns, 1e6 * x.per_step_ms / (20 * N^3))
        end
        push!(cells, isempty(ns) ? "—" : @sprintf("%.1f–%.1f", minimum(ns), maximum(ns)))
    end
    md_table(io, vcat(["quantity"], devices), [cells])

    # -- Size ----------------------------------------------------------------
    println(io, "## Implicit size scaling: quasi-static CG+AMG at 823k and 1.57M DOF\n")
    rows = []
    for c in ("cube64-qs", "cube80-qs")
        cells = Any[c == "cube64-qs" ? "cube64 (823k)" : "cube80 (1.57M)"]
        for d in devices
            r = findfirst(x -> label(x) == d && x.case == c, recs)
            push!(cells, r === nothing ? "—" :
                  (recs[r].ok ? "$(fmt(recs[r].t_total)) s / $(round(Int, recs[r].cg)) CG / $(gb(recs[r].vram)) GB" :
                                "failed: $(recs[r].failure)"))
        end
        push!(rows, cells)
    end
    md_table(io, vcat(["case"], devices), rows)
    println(io, "Cells are total wall / CG iterations / live device memory.\n")
end

function main()
    recs = read_matrix()
    isempty(recs) && error("no records under $(relpath(MATRIX, REPO))")
    if "--write" in ARGS
        open(io -> render(io, recs), OUT, "w")
        println("wrote ", relpath(OUT, REPO), " from ", length(recs), " records")
    else
        render(stdout, recs)
    end
end

main()
