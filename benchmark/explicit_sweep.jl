# Explicit-dynamics CPU-vs-GPU scaling sweep on the torsion bar.
#
# One (size, device) run per fresh process, appending a JSON-lines record to
# benchmark/results/<tag>.jsonl -- same contract as harness.jl.
#
# Usage:
#   julia --project=. benchmark/explicit_sweep.jl <N> <cpu|rocm|cuda> <tag> \
#         [nsteps] [threads]
#
# N is the torsion-bar refinement (elements across the section; see
# torsiongen.jl).  N=20 is the checked-in 530k-DOF torsion.g.  The mesh is
# generated on demand into benchmark/meshes/.
#
# Method notes:
#   * The time step scales as 1/N so the CFL number stays fixed across sizes;
#     cost per step is therefore the only thing that varies with refinement.
#   * The run is split into two equal control intervals.  The first is warm-up
#     (first-touch allocation, device warm-up) and the second is the measured
#     one -- both are recorded so the spread is visible.
#   * Output is stripped to nodal displacement with no recovery, so the single
#     Exodus write inside the measured interval is negligible.

# Minimal JSON emission for flat records — same emitter as harness.jl, so the
# two result families stay readable by the same tooling without a dependency.
_json(x::Union{Real, Bool}) = string(x)
_json(::Nothing) = "null"
_json(x::AbstractString) = "\"" * replace(x, "\\" => "\\\\", "\"" => "\\\"") * "\""
_json(x::AbstractVector) = "[" * join(map(_json, x), ",") * "]"
_json(nt::NamedTuple) =
    "{" * join(("\"$(k)\":" * _json(v) for (k, v) in pairs(nt)), ",") * "}"

include(joinpath(@__DIR__, "torsiongen.jl"))

const REPO      = dirname(@__DIR__)
# On machines whose home is NFS/GPFS (the ascicgpu hosts), benchmark I/O must
# stay off the shared filesystem: the measured interval contains one Exodus
# write, and multi-GB meshes are read at setup.  CARINA_BENCH_SCRATCH points
# all generated artifacts (meshes, decks, outputs, results) at a local disk;
# unset, everything lands in the repo as before.
const SCRATCH   = get(ENV, "CARINA_BENCH_SCRATCH", @__DIR__)
const MESH_DIR  = joinpath(SCRATCH, "meshes")
const INPUT_DIR = joinpath(SCRATCH, "inputs")
const RESULTS   = joinpath(SCRATCH, "results")

# CFL-invariant step: N=20 (h = 2.5e-3) is stable at 5e-7 with the material
# below (dilatational wave speed ~1095 m/s => CFL ~0.22).
time_step(N::Int) = 5.0e-7 * 20 / N

function ensure_mesh(N::Int)
    mkpath(MESH_DIR)
    path = joinpath(MESH_DIR, "torsion$(N).g")
    isfile(path) || generate(N, path)
    return path
end

function write_deck(N::Int, nsteps::Int)
    mkpath(INPUT_DIR)
    mesh = ensure_mesh(N)
    dt   = time_step(N)
    name = "explicit-torsion-n$(N)"
    path = joinpath(INPUT_DIR, "$name.yaml")
    # Two control intervals: warm-up then measured.
    interval = (nsteps ÷ 2) * dt
    deck = """
    # $name -- generated by benchmark/explicit_sweep.jl.  Do not edit by hand.
    # $(N)x$(N)x$(20N) hex torsion bar, central difference, $nsteps steps.
    type: single
    input mesh file: $(relpath(mesh, INPUT_DIR))
    output mesh file: $name.e
    output interval: $interval
    output:
      stress: false
      deformation gradient: false
      recovery: none
    model:
      type: solid mechanics
      material:
        blocks:
          torsion: neohookean
        neohookean:
          elastic modulus: 1.0e9
          density: 1000.0
          Poisson's ratio: 0.25
    time integrator:
      type: central difference
      time step: $dt
      initial time: 0.0
      final time: $(nsteps * dt)
    initial conditions:
      velocity:
        - node set: nsall
          function: "a=8000; -a*y*z"
          component: x
        - node set: nsall
          function: "a=8000; a*x*z"
          component: y
        - node set: nsall
          function: "0.0"
          component: z
    """
    write(path, deck)
    return path
end

# "12.34s" / "2m 34.56s" / "1h 2m 3.45s" / "1d 2h 3m 4.56s" -> seconds
function parse_wall(s::AbstractString)
    total = 0.0
    for m in eachmatch(r"([0-9]+\.?[0-9]*)([dhms])", s)
        v = parse(Float64, m.captures[1])
        total += v * (m.captures[2] == "d" ? 86400 :
                      m.captures[2] == "h" ? 3600 :
                      m.captures[2] == "m" ? 60 : 1)
    end
    return total
end

function main()
    length(ARGS) >= 3 || error(
        "Usage: explicit_sweep.jl <N> <cpu|rocm|cuda> <tag> [nsteps] [threads]")
    N       = parse(Int, ARGS[1])
    device  = ARGS[2]
    tag     = ARGS[3]
    nsteps  = length(ARGS) >= 4 ? parse(Int, ARGS[4]) : 200
    threads = length(ARGS) >= 5 ? parse(Int, ARGS[5]) : 12
    iseven(nsteps) || error("nsteps must be even (two equal control intervals)")

    deck = write_deck(N, nsteps)
    cmd  = `$(joinpath(REPO, "bin", "carina")) $deck --device $device --threads $threads`
    @info "Running" N device nsteps threads deck

    out = IOBuffer()
    t0  = time()
    ok  = success(pipeline(cmd; stdout = out, stderr = out))
    wall_total = time() - t0
    log = String(take!(out))
    println(log)

    walls = [parse_wall(m.captures[1])
             for m in eachmatch(r"\[STOP\].*wall = ([^\n:]+?)\s*$"m, log)]
    setup = let m = match(r"\[SETUP\]\s+Setup complete \(([^)]+)\)", log)
        m === nothing ? nothing : parse_wall(m.captures[1])
    end

    nn = (N + 1)^2 * (20N + 1)
    # Second interval is the measured one; the first is warm-up.
    measured   = length(walls) >= 2 ? walls[2] : nothing
    per_step_ms = measured === nothing ? nothing : 1000 * measured / (nsteps ÷ 2)
    rec = (
        case           = "explicit-torsion",
        N              = N,
        n_elems        = N * N * 20N,
        n_nodes        = nn,
        n_dof          = 3nn,
        device         = device,
        threads        = threads,
        n_steps        = nsteps,
        time_step      = time_step(N),
        ok             = ok,
        setup_s        = setup,
        interval_walls = walls,
        measured_s     = measured,
        per_step_ms    = per_step_ms,
        wall_total_s   = wall_total,
    )
    mkpath(RESULTS)
    open(joinpath(RESULTS, "$tag.jsonl"), "a") do io
        println(io, _json(rec))
    end
    @info "Recorded" measured per_step_ms ok
    ok || exit(1)
end

if abspath(PROGRAM_FILE) == @__FILE__
    main()
end
